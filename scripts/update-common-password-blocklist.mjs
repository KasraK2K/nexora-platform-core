import { createHash } from 'node:crypto';
import { mkdir, writeFile } from 'node:fs/promises';
import path from 'node:path';

const SOURCE_URL =
  'https://raw.githubusercontent.com/danielmiessler/SecLists/refs/heads/master/Passwords/Common-Credentials/100k-most-used-passwords-NCSC.txt';
const OUTPUT_PATH = path.resolve(
  'src/modules/authentication/infrastructure/common-password-hashes.generated.ts',
);
const MIN_CODE_POINTS = 15;
const MAX_CODE_POINTS = 128;
const MAX_BYTES = 512;

const response = await fetch(SOURCE_URL, {
  headers: {
    'User-Agent': 'NexoraPlatformCore-password-blocklist-updater/1.0',
  },
  redirect: 'error',
  signal: AbortSignal.timeout(30_000),
});

if (!response.ok) {
  throw new Error(
    `Password-list download failed with HTTP ${response.status}.`,
  );
}

const sourceBytes = new Uint8Array(await response.arrayBuffer());
const sourceSha256 = sha256(sourceBytes);
const sourceText = new TextDecoder('utf-8', { fatal: true }).decode(
  sourceBytes,
);
const sourcePasswords = sourceText.split(/\r?\n/);

if (sourcePasswords.length < 50_000) {
  throw new Error('Password-list download contained too few entries.');
}

const hashes = [
  ...new Set(
    sourcePasswords
      .map((password) => password.normalize('NFC').toLocaleLowerCase('en-US'))
      .filter((password) => {
        const codePointLength = [...password].length;
        return (
          codePointLength >= MIN_CODE_POINTS &&
          codePointLength <= MAX_CODE_POINTS &&
          Buffer.byteLength(password, 'utf8') <= MAX_BYTES
        );
      })
      .map((password) => sha256(password)),
  ),
].sort();

const generated = `// Generated by scripts/update-common-password-blocklist.mjs. Do not edit manually.
// Source: ${SOURCE_URL}
// Source SHA-256: ${sourceSha256}
// Filter: NFC + en-US lowercase; ${MIN_CODE_POINTS}-${MAX_CODE_POINTS} Unicode code points; <= ${MAX_BYTES} UTF-8 bytes.
// Entries: ${hashes.length}

export const COMMON_PASSWORD_SHA256_HASHES: readonly string[] = [
${hashes.map((hash) => `  '${hash}',`).join('\n')}
];
`;

await mkdir(path.dirname(OUTPUT_PATH), { recursive: true });
await writeFile(OUTPUT_PATH, generated, 'utf8');
console.log(
  `Wrote ${hashes.length} password hashes from source ${sourceSha256}.`,
);

function sha256(value) {
  return createHash('sha256').update(value).digest('hex');
}
